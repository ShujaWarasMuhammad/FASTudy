// Google Gemini AI Client for FASTudy
// Generates live explanations, hints, variable traces, and interactive conversational tutoring

const GEMINI_API_KEY = import.meta.env.VITE_GEMINI_API_KEY;

export async function askGeminiTutor({
  question,
  userQuery = '',
  conversationHistory = [],
  mode = 'explain', // 'explain' | 'hint' | 'trace' | 'chat'
}) {
  if (!GEMINI_API_KEY) {
    return {
      success: false,
      error: 'Gemini API key is not configured. Add VITE_GEMINI_API_KEY to your .env.local file.',
    };
  }

  const GEMINI_ENDPOINT = `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${GEMINI_API_KEY}`;
  const systemContext = `
You are the FASTudy AI Tutor, an expert Computer Science and Mathematics instructor at FAST NUCES.
You help students master C/C++ dry runs, variable tracing, pointers, recursion, Calculus limits/derivatives, and Physics mechanics.

Problem Context:
- Title: ${question.title || ''}
- Type: ${question.type || ''}
- Problem Statement: ${question.statement || question.description || ''}
- Code Snippet:
${question.code || question.starterCode || 'None'}
- LaTeX Formula: ${question.latexExpression || 'None'}
- Expected Output / Answer: ${question.expectedOutput || 'None'}
- Solution Walkthrough: ${question.explanation || 'None'}

Instructions:
1. Provide concise, clear, and high-yield explanations.
2. If the user asks for a hint, don't give the direct answer immediately; guide their reasoning.
3. For dry runs, explain the step-by-step state changes of variables in execution order.
4. For mathematical limits, specify algebraic techniques (factoring, L'Hopital, conjugate multiplication).
5. Format responses in clean Markdown: use short ##/### headings, concise numbered steps for traces, and bullets only where useful.
6. Wrap every mathematical expression in LaTeX delimiters: inline math as $...$ and standalone equations as $$...$$. Prefer LaTeX over Unicode math symbols.
7. Format code blocks in markdown with \`\`\`c or \`\`\`cpp. Keep answers skimmable and avoid filler.
`;

  let prompt = '';
  if (mode === 'hint') {
    prompt = 'Give me a subtle hint to point me in the right direction without spoiling the exact answer.';
  } else if (mode === 'trace') {
    prompt = 'Provide a step-by-step execution trace showing how variable states change line-by-line.';
  } else if (mode === 'explain') {
    prompt = 'Explain the core logic, theory, and intuition behind this problem in a clear, easy-to-digest manner.';
  } else if (userQuery) {
    prompt = userQuery;
  } else {
    prompt = 'Help me understand how to evaluate this problem.';
  }

  const contents = [
    {
      role: 'user',
      parts: [{ text: `${systemContext}\n\nStudent Query: ${prompt}` }],
    },
  ];

  // Append history if conversational chat
  if (conversationHistory.length > 0) {
    conversationHistory.forEach((msg) => {
      contents.push({
        role: msg.role === 'ai' ? 'model' : 'user',
        parts: [{ text: msg.text }],
      });
    });
    if (userQuery) {
      contents.push({
        role: 'user',
        parts: [{ text: userQuery }],
      });
    }
  }

  try {
    const res = await fetch(GEMINI_ENDPOINT, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ contents }),
    });

    if (!res.ok) {
      const errData = await res.json();
      throw new Error(errData.error?.message || `API error ${res.status}`);
    }

    const data = await res.json();
    const replyText =
      data.candidates?.[0]?.content?.parts?.[0]?.text ||
      'No response generated by tutor.';

    return { success: true, text: replyText };
  } catch (error) {
    console.error('Gemini AI Tutor error:', error);
    return {
      success: false,
      error: error.message || 'Failed to reach AI Tutor. Check connectivity.',
    };
  }
}
